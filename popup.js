function loadFontInPopup(fontFamily) {
  if (!fontFamily || fontFamily === "default" || fontFamily.includes("system-ui")) return;

  const match = fontFamily.match(/'([^']+)'/);
  const fontName = match ? match[1] : fontFamily.split(',')[0].trim();
  const fontId = `arizona-styler-font-${fontName.toLowerCase().replace(/\s+/g, '-')}`;

  if (document.getElementById(fontId)) return;

  const fontLink = document.createElement("link");
  fontLink.id = fontId;
  fontLink.rel = "stylesheet";
  fontLink.href = `https://fonts.googleapis.com/css2?family=${fontName.replace(/\s+/g, '+')}:wght@300;400;500;600;700&display=swap`;

  document.head.appendChild(fontLink);
}


function applyThemeToPopup(settings) {
  if (!settings) return;
  const root = document.documentElement;
  const mode = settings.mode || "dark";

  const textSecondary = mode === "dark" ? "rgba(255, 255, 255, 0.6)" : "rgba(0, 0, 0, 0.6)";
  const borderOpacity = mode === "dark" ? "rgba(255, 255, 255, 0.08)" : "rgba(0, 0, 0, 0.08)";
  const borderFocus = settings.accent1 + "66";

  root.style.setProperty("--pop-bg", settings.bg);
  root.style.setProperty("--pop-card-bg", settings.block);
  root.style.setProperty("--pop-border", borderOpacity);
  root.style.setProperty("--pop-border-focus", borderFocus);
  root.style.setProperty("--pop-text", settings.text);
  root.style.setProperty("--pop-text-secondary", textSecondary);
  root.style.setProperty("--pop-accent", settings.accent1);
  root.style.setProperty("--pop-accent2", settings.accent2);
  root.style.setProperty("--pop-accent-gradient", `linear-gradient(135deg, ${settings.accent1} 0%, ${settings.accent2} 100%)`);
  const accentLuminances = [settings.accent1, settings.accent2].map(hex => {
    const expanded = hex.length === 4 ? "#" + [...hex.slice(1)].map(channel => channel + channel).join("") : hex;
    const channels = expanded.slice(1).match(/.{2}/g).map(channel => {
      const value = parseInt(channel, 16) / 255;
      return value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4;
    });
    return channels[0] * 0.2126 + channels[1] * 0.7152 + channels[2] * 0.0722;
  });
  const darkContrast = (Math.min(...accentLuminances) + 0.05) / 0.05;
  const lightContrast = 1.05 / (Math.max(...accentLuminances) + 0.05);
  root.style.setProperty("--pop-accent-text", lightContrast >= 3 || lightContrast >= darkContrast ? "#ffffff" : "#000000");


  if (settings.fontWeight && settings.fontWeight !== "default") {
    root.style.setProperty("--pop-font-weight", settings.fontWeight);
  } else {
    root.style.removeProperty("--pop-font-weight");
  }


  if (settings.font && settings.font !== "default") {
    loadFontInPopup(settings.font);
    root.style.setProperty("--pop-font-family", settings.font);
  } else {
    root.style.removeProperty("--pop-font-family");
  }


  const baseRadius = settings.radius !== undefined ? settings.radius : 8;
  root.style.setProperty("--pop-radius", baseRadius + "px");
  root.style.setProperty("--pop-radius-small", Math.max(2, baseRadius - 2) + "px");
  root.style.setProperty("--pop-radius-micro", Math.max(1, baseRadius - 4) + "px");

  const popupHexToRgb = (hex) => {
    hex = hex.replace(/^#/, '');
    if (hex.length === 3) hex = hex[0] + hex[0] + hex[1] + hex[1] + hex[2] + hex[2];
    let r = parseInt(hex.substring(0, 2), 16);
    let g = parseInt(hex.substring(2, 4), 16);
    let b = parseInt(hex.substring(4, 6), 16);
    return `${r}, ${g}, ${b}`;
  };

  root.style.setProperty("--arizona-styler-bg", settings.bg);
  root.style.setProperty("--arizona-styler-block", settings.block);
  root.style.setProperty("--arizona-styler-accent1", settings.accent1);
  root.style.setProperty("--arizona-styler-accent2", settings.accent2);
  root.style.setProperty("--arizona-styler-text", settings.text);
  root.style.setProperty("--arizona-styler-radius", baseRadius + "px");
  root.style.setProperty("--arizona-styler-border", borderOpacity);

  root.style.setProperty("--arizona-styler-accent1-rgb", popupHexToRgb(settings.accent1));
  root.style.setProperty("--arizona-styler-accent2-rgb", popupHexToRgb(settings.accent2));
  root.style.setProperty("--arizona-styler-block-rgb", popupHexToRgb(settings.block));
  root.style.setProperty("--arizona-styler-bg-rgb", popupHexToRgb(settings.bg));

  const body = document.body;
  if (body) {
    body.style.backgroundImage = `
      radial-gradient(circle at 100% 0%, ${settings.accent2}14 0%, transparent 40%),
      radial-gradient(circle at 0% 100%, ${settings.accent1}14 0%, transparent 40%)
    `;
  }
}


function exportCustomTheme(themeData) {
  try {
    const jsonStr = JSON.stringify(themeData);
    const code = btoa(unescape(encodeURIComponent(jsonStr)));
    navigator.clipboard.writeText(code).then(() => {
      alert("Код темы успешно скопирован в буфер обмена!");
    }).catch(err => {
      console.error("Clipboard copy failed: ", err);
      prompt("Код вашей темы (скопируйте его вручную):", code);
    });
  } catch (err) {
    console.error(err);
    alert("Ошибка при экспорте темы.");
  }
}

function getRandomThemeColors(mode) {
  const h1 = Math.floor(Math.random() * 360);
  const h2 = (h1 + 60 + Math.floor(Math.random() * 120)) % 360;

  const accent1 = hslToHex(h1, 85, 55);
  const accent2 = hslToHex(h2, 85, 55);

  let bg, block, text;
  if (mode === "dark") {
    const bgHue = Math.floor(Math.random() * 360);
    const bgSat = 5 + Math.floor(Math.random() * 15);
    const bgLight = 5 + Math.floor(Math.random() * 7);
    bg = hslToHex(bgHue, bgSat, bgLight);
    block = hslToHex(bgHue, bgSat, bgLight + 5);
    text = hslToHex(bgHue, 10, 85 + Math.floor(Math.random() * 10));
  } else {
    const bgHue = Math.floor(Math.random() * 360);
    const bgSat = 3 + Math.floor(Math.random() * 7);
    const bgLight = 92 + Math.floor(Math.random() * 5);
    bg = hslToHex(bgHue, bgSat, bgLight);
    block = "#ffffff";
    text = hslToHex(bgHue, 15, 10 + Math.floor(Math.random() * 10));
  }

  return { bg, block, accent1, accent2, text };
}

function hslToHex(h, s, l) {
  s /= 100;
  l /= 100;
  let c = (1 - Math.abs(2 * l - 1)) * s;
  let x = c * (1 - Math.abs((h / 60) % 2 - 1));
  let m = l - c / 2;
  let r = 0, g = 0, b = 0;
  if (0 <= h && h < 60) { r = c; g = x; b = 0; }
  else if (60 <= h && h < 120) { r = x; g = c; b = 0; }
  else if (120 <= h && h < 180) { r = 0; g = c; b = x; }
  else if (180 <= h && h < 240) { r = 0; g = x; b = c; }
  else if (240 <= h && h < 300) { r = x; g = 0; b = c; }
  else if (300 <= h && h < 360) { r = c; g = 0; b = x; }

  let rHex = Math.round((r + m) * 255).toString(16).padStart(2, '0');
  let gHex = Math.round((g + m) * 255).toString(16).padStart(2, '0');
  let bHex = Math.round((b + m) * 255).toString(16).padStart(2, '0');

  return `#${rHex}${gHex}${bHex}`;
}

function renderParsedNavbarToggles() {
  const container = document.getElementById("nav-toggle-grid");
  if (!container) return;

  chrome.storage.local.get("parsedNavbarButtons", (data) => {
    const buttons = data.parsedNavbarButtons || [];
    if (buttons.length === 0) {
      container.innerHTML = `<div style="grid-column: span 2; font-size: 11px; color: var(--pop-text-secondary); text-align: center; padding: 4px;">Откройте страницу форума для парсинга кнопок</div>`;
      return;
    }

    container.innerHTML = "";
    const hiddenIds = globalTweaks.hiddenNavIds || [];
    const hiddenSet = new Set(hiddenIds);

    buttons.forEach(btn => {
      const label = document.createElement("label");
      label.className = "checkbox-container";

      const cb = document.createElement("input");
      cb.type = "checkbox";
      cb.checked = hiddenSet.has(btn.id);

      cb.addEventListener("change", () => {
        if (cb.checked) {
          if (!hiddenSet.has(btn.id)) {
            hiddenIds.push(btn.id);
          }
        } else {
          const idx = hiddenIds.indexOf(btn.id);
          if (idx > -1) {
            hiddenIds.splice(idx, 1);
          }
        }
        globalTweaks.hiddenNavIds = hiddenIds;
        markAsCustom();
        saveAndBroadcast();
      });

      label.appendChild(cb);
      label.appendChild(document.createTextNode(" " + btn.name));
      container.appendChild(label);
    });
  });
}

function renderCustomNavInPopup() {
  const listContainer = document.getElementById("custom-nav-list");
  if (!listContainer) return;

  const items = globalTweaks.customNavItems || [];
  if (items.length === 0) {
    listContainer.innerHTML = `<div style="font-size: 11px; color: var(--pop-text-secondary); text-align: center; padding: 4px;">Нет кастомных кнопок</div>`;
    return;
  }

  listContainer.innerHTML = "";
  items.forEach(item => {
    const row = document.createElement("div");
    row.className = "custom-nav-row";

    row.innerHTML = `
      <span title="${item.url}">${item.name}</span>
      <button class="delete-nav-btn" data-id="${item.id}">&times;</button>
    `;

    row.querySelector(".delete-nav-btn").addEventListener("click", () => {
      globalTweaks.customNavItems = globalTweaks.customNavItems.filter(i => i.id !== item.id);
      markAsCustom();
      saveAndBroadcast();
      renderCustomNavInPopup();
    });

    listContainer.appendChild(row);
  });
}

