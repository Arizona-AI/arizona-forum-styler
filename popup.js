function loadSettings() {
  chrome.storage.local.get(["enabled", "activeThemeId", "customThemes", "currentSettings", "globalBgSettings", "globalTweaks", "favoritePresets"], (data) => {
    if (data.enabled !== undefined) extensionEnabled = data.enabled;
    if (data.activeThemeId !== undefined) activeThemeId = data.activeThemeId;
    if (data.customThemes !== undefined) customThemes = data.customThemes;
    if (data.favoritePresets !== undefined) favoritePresets = data.favoritePresets;

    if (data.globalTweaks !== undefined) {
      globalTweaks = { ...DEFAULT_TWEAKS, ...data.globalTweaks };
    } else {
      globalTweaks = { ...DEFAULT_TWEAKS };
    }

    extensionToggle.checked = extensionEnabled;
    toggleStatusText.textContent = extensionEnabled ? "Вкл" : "Выкл";
    toggleStatusText.style.color = extensionEnabled ? "var(--pop-accent)" : "var(--pop-text-secondary)";

    if (data.currentSettings !== undefined) {
      currentSettings = { ...DEFAULT_SETTINGS, ...data.currentSettings };
    } else {
      currentSettings = { ...DEFAULT_SETTINGS, ...PRESETS[activeThemeId] };
      if (PRESETS[activeThemeId]) {
        if (currentSettings.font && currentSettings.font !== "default") {
          currentSettings.fontApply = "exclude-messages";
        }
      }
    }

    if (data.currentSettings === undefined || data.currentSettings.bgType === undefined) {
      if (data.globalBgSettings !== undefined) {
        currentSettings.bgType = data.globalBgSettings.bgType || "color";
        currentSettings.bgUrl = data.globalBgSettings.bgUrl || "";
        currentSettings.bgOpacity = data.globalBgSettings.bgOpacity !== undefined ? data.globalBgSettings.bgOpacity : 40;
      }
    }

    renderPresets();
    renderSavedThemes();
    updateCustomizerUI(currentSettings);
    updateBackgroundUI(currentSettings);
    updateTweaksUI();

    updateActiveThemeDisplay();
    applyThemeToPopup(currentSettings);
  });
}


function saveAndBroadcast() {
  globalBgSettings = {
    bgType: currentSettings.bgType || "color",
    bgUrl: currentSettings.bgUrl || "",
    bgOpacity: currentSettings.bgOpacity !== undefined ? currentSettings.bgOpacity : 40,
    bgHue: currentSettings.bgHue ?? 0
  };

  chrome.storage.local.set({
    enabled: extensionEnabled,
    activeThemeId: activeThemeId,
    currentSettings: currentSettings,
    globalBgSettings: globalBgSettings,
    globalTweaks: globalTweaks,
    customThemes: customThemes,
    favoritePresets: favoritePresets
  }, () => {
    updateActiveThemeDisplay();
    broadcastToTabs();
    applyThemeToPopup(currentSettings);
  });
}


function broadcastToTabs() {
  chrome.tabs.query({ url: ["*://forum.arizona-rp.com/*", "*://*.forum.arizona-rp.com/*"] }, (tabs) => {
    tabs.forEach((tab) => {
      chrome.tabs.sendMessage(tab.id, {
        type: "APPLY_THEME",
        enabled: extensionEnabled,
        settings: currentSettings,
        bgSettings: globalBgSettings,
        tweaks: globalTweaks,
        activeThemeId: activeThemeId
      }, () => {
        void chrome.runtime.lastError;
      });
    });
  });
}

