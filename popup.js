function toggleFavorite(presetId) {
  const index = favoritePresets.indexOf(presetId);
  if (index === -1) {
    favoritePresets.push(presetId);
  } else {
    favoritePresets.splice(index, 1);
  }
  saveAndBroadcast();
  renderPresets();
}


function renderPresets() {
  presetsGridFavorites.innerHTML = "";
  presetsGridDark.innerHTML = "";
  presetsGridLight.innerHTML = "";

  const searchQuery = (presetSearchInput.value || "").toLowerCase().trim();

  let favCount = 0;
  let darkCount = 0;
  let lightCount = 0;

  Object.values(PRESETS).forEach(preset => {
    const matchesSearch = preset.name.toLowerCase().includes(searchQuery);
    if (!matchesSearch) return;

    const isFavorite = favoritePresets.includes(preset.id);


    if (isFavorite) {
      const favCard = createPresetCard(preset);
      presetsGridFavorites.appendChild(favCard);
      favCount++;
    }


    const card = createPresetCard(preset);
    if (preset.mode === "light") {
      presetsGridLight.appendChild(card);
      lightCount++;
    } else {
      presetsGridDark.appendChild(card);
      darkCount++;
    }
  });


  favoritesSection.style.display = favCount > 0 ? "block" : "none";
  darkPresetsSection.style.display = darkCount > 0 ? "block" : "none";
  lightPresetsSection.style.display = lightCount > 0 ? "block" : "none";
}


function renderSavedThemes() {
  const customIds = Object.keys(customThemes);
  if (customIds.length === 0) {
    savedThemesSection.style.display = "none";
    return;
  }

  savedThemesSection.style.display = "block";
  savedThemesList.innerHTML = "";

  customIds.forEach(id => {
    const theme = customThemes[id];

    const item = document.createElement("div");
    item.className = `saved-theme-item ${activeThemeId === id ? "active" : ""}`;
    item.setAttribute("data-id", id);

    item.innerHTML = `
      <div class="saved-theme-info">
        <span class="saved-theme-color-dot" style="background: linear-gradient(135deg, ${theme.accent1} 0%, ${theme.accent2} 100%)"></span>
        <span class="saved-theme-name">${theme.name}</span>
      </div>
      <div style="display: flex; align-items: center;">
        <button class="export-theme-btn" title="Копировать код темы" data-id="${id}">
          <span class="export-theme-icon"></span>
        </button>
        <button class="delete-theme-btn" title="Удалить тему" data-id="${id}">×</button>
      </div>
    `;


    item.addEventListener("click", (e) => {
      if (e.target.closest(".delete-theme-btn") || e.target.closest(".export-theme-btn")) return;
      selectTheme(id, theme);
    });


    item.querySelector(".export-theme-btn").addEventListener("click", (e) => {
      e.stopPropagation();
      exportCustomTheme(theme);
    });


    item.querySelector(".delete-theme-btn").addEventListener("click", (e) => {
      e.stopPropagation();
      deleteCustomTheme(id);
    });

    savedThemesList.appendChild(item);
  });
}


function selectTheme(themeId, themeData) {
  activeThemeId = themeId;
  currentSettings = { ...DEFAULT_SETTINGS, ...themeData };

  if (PRESETS[themeId]) {
    if (currentSettings.font && currentSettings.font !== "default") {
      currentSettings.fontApply = "exclude-messages";
    }
  }

  globalTweaks = { ...DEFAULT_TWEAKS, ...(themeData.tweaks || {}) };

  updateCustomizerUI(currentSettings);
  updateBackgroundUI(currentSettings);
  updateTweaksUI();

  document.querySelectorAll(".preset-card").forEach(c => {
    c.classList.toggle("active", c.getAttribute("data-id") === themeId);
  });
  document.querySelectorAll(".saved-theme-item").forEach(c => {
    c.classList.toggle("active", c.getAttribute("data-id") === themeId);
  });

  saveAndBroadcast();
}


